menu = {
    "番茄炒蛋":{
"食材":["番茄","鸡蛋","盐","糖"],
"做法":"\n1.番茄切块\n2.炒鸡蛋"
    },
    "红烧肉":{
"食材":["五花肉","酱油","冰糖"],
"做法":"\n1.五花肉焯水\n2.炒糖色"
    },
    "宫保鸡丁":{
"食材":["鸡胸肉","花生","干辣椒"],
"做法":"\n1.鸡胸肉切丁腌制\n2.炒花生备用\n3.爆香干辣椒\n4.加入鸡丁翻炒\n5.加花生出锅"
    }
}

print("🍳 我们的家庭菜谱 🍳")
for 菜名, 信息 in menu.items():
    print(f"【{菜名}】")
    print(f"  食材：{', '.join(信息['食材'])}")
    print(f"  做法：{信息['做法']}")
    print("-" * 30)

    # 删除菜谱
菜名 = input("请输入要删除的菜名：")
if 菜名 in menu:
    del menu[菜名]
    print(f"已删除 {菜名}")
else:
    print(f"未找到 {菜名}")

    # 修改菜谱
菜名 = input("请输入要修改的菜名：")
if 菜名 in menu:
    新食材 = input("请输入新的食材（用英文逗号分隔）：").split(",")
    新做法 = input("请输入新的做法（用 \\n 分隔步骤）：")
    menu[菜名]["食材"] = 新食材
    menu[菜名]["做法"] = "\n" + 新做法
    print(f"{菜名}已更新！")
    print(f"食材：{menu[菜名]['食材']}")
    print(f"做法：{menu[菜名]['做法']}")
else:
    print(f"未找到 {菜名}")